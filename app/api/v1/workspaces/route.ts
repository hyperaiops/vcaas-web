import path from "node:path";
import fs from "node:fs/promises";
import { randomBytes } from "node:crypto";
import { jsonResponse, errorResponse } from "@/app/lib/workspace/api-helpers";
import {
  listWorkspaces,
  createWorkspace,
  WorkspaceError,
} from "@/app/lib/db";
import { isValidWorkspaceId, type WorkspaceRow } from "@/app/lib/workspace/types";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

function publicWorkspace(row: WorkspaceRow) {
  return {
    id: row.id,
    name: row.name,
    revision: row.revision,
    createdAt: row.createdAt,
    updatedAt: row.updatedAt,
  };
}

export async function GET() {
  const workspaces = listWorkspaces();
  return jsonResponse({ apiVersion: "v1", workspaces: workspaces.map(publicWorkspace) });
}

function templateDir(): string {
  return path.resolve(process.env.TEMPLATE_DIR ?? path.join(process.cwd(), "template"));
}

function workspacesRoot(): string {
  return path.resolve(process.env.WORKSPACE_FILES_ROOT ?? path.join(process.cwd(), ".data", "workspaces"));
}

// Names that are never copied when scaffolding a workspace from the template.
// node_modules/.next/out are large and regenerated by `pnpm install`/build
// inside the WebContainer; tsconfig.tsbuildinfo and package-lock.json are
// local build artifacts. Keeping the copy to just source files makes create
// instant instead of copying hundreds of MB.
const SKIP_NAMES = new Set([
  "node_modules",
  ".next",
  "out",
  ".git",
  "tsconfig.tsbuildinfo",
  "package-lock.json",
]);

async function copyTemplate(dest: string): Promise<void> {
  const src = templateDir();
  await fs.mkdir(dest, { recursive: true });
  await fs.cp(src, dest, {
    recursive: true,
    filter: (source) => {
      const name = path.basename(source);
      // Always copy the root (src === template dir, basename may be "template").
      if (source === src) return true;
      return !SKIP_NAMES.has(name);
    },
  });
}

// POST /api/v1/workspaces — create a new workspace from the template.
// Body: { name: string, id?: string }
export async function POST(request: Request) {
  let body: { name?: unknown; id?: unknown };
  try {
    body = await request.json();
  } catch {
    return errorResponse(400, "INVALID_REQUEST", "The request body must be valid JSON.");
  }
  const name = typeof body.name === "string" ? body.name.trim() : "";
  if (!name) {
    return errorResponse(400, "INVALID_REQUEST", "A non-empty 'name' is required.");
  }
  const id = typeof body.id === "string" ? body.id.trim() : "";
  if (id && !isValidWorkspaceId(id)) {
    return errorResponse(400, "INVALID_WORKSPACE_ID", "Workspace ID must contain only lowercase letters, digits, and hyphens.");
  }

  // Derive an id from the name if none provided, and ensure uniqueness by
  // appending a short suffix until the directory/row is free.
  const baseId = id || name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "") || "workspace";
  const root = workspacesRoot();
  await fs.mkdir(root, { recursive: true });

  let finalId = baseId;
  let attempt = 0;
  // createWorkspace rejects duplicate ids/root_paths; if the user gave an
  // explicit id that collides, surface the error rather than silently
  // mangling it.
  if (id) {
    finalId = id;
  } else {
    while (true) {
      const candidate = attempt === 0 ? baseId : `${baseId}-${randomSuffix()}`;
      const candidatePath = path.join(root, candidate);
      try {
        await fs.access(candidatePath);
        attempt++;
        continue;
      } catch {
        finalId = candidate;
        break;
      }
    }
  }

  const workspacePath = path.join(root, finalId);
  try {
    await copyTemplate(workspacePath);
  } catch (error) {
    return errorResponse(500, "WORKSPACE_CREATE_FAILED", `Unable to scaffold the workspace: ${error instanceof Error ? error.message : String(error)}`);
  }

  try {
    const row = createWorkspace({ id: finalId, name, rootPath: workspacePath });
    return jsonResponse({ apiVersion: "v1", workspace: publicWorkspace(row) }, 201);
  } catch (error) {
    // Roll back the copied template directory if the DB insert failed.
    await fs.rm(workspacePath, { recursive: true, force: true });
    if (error instanceof WorkspaceError) {
      return errorResponse(409, error.code, error.message);
    }
    return errorResponse(500, "WORKSPACE_CREATE_FAILED", "Unable to create the workspace.");
  }
}

function randomSuffix(): string {
  return cryptoRandom(3);
}

function cryptoRandom(bytes: number): string {
  return randomBytes(bytes).toString("hex");
}
